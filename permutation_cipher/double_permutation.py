import os
import tkinter as tk
from tkinter import messagebox

# Очищення екрану під час запуску
os.system('cls' if os.name == 'nt' else 'clear')

def проста_перестановка(текст: str, ключ: str) -> str:
    стовпці = len(ключ)
    рядки = (len(текст) + стовпці - 1) // стовпці
    матриця = [[' ' for _ in range(стовпці)] for _ in range(рядки)]
    
    індекс = 0
    for р in range(рядки):
        for с in range(стовпці):
            if індекс < len(текст):
                матриця[р][с] = текст[індекс]
                індекс += 1

    упорядкований_ключ = sorted(list(ключ))
    результат = ""
    for літера in упорядкований_ключ:
        кол = ключ.index(літера)
        for р in range(рядки):
            результат += матриця[р][кол]
    return результат

def зворотна_перестановка(текст: str, ключ: str) -> str:
    стовпці = len(ключ)
    рядки = (len(текст) + стовпці - 1) // стовпці
    матриця = [[' ' for _ in range(стовпці)] for _ in range(рядки)]

    упорядкований_ключ = sorted(list(ключ))
    індекс = 0
    for літера in упорядкований_ключ:
        кол = ключ.index(літера)
        for р in range(рядки):
            if індекс < len(текст):
                матриця[р][кол] = текст[індекс]
                індекс += 1

    результат = "".join("".join(рядок) for рядок in матриця)
    return результат.strip()

def подвійна_перестановка(текст, ключ1, ключ2, дія):
    if дія == "шифрувати":
        return проста_перестановка(проста_перестановка(текст, ключ1), ключ2)
    else:
        return зворотна_перестановка(зворотна_перестановка(текст, ключ2), ключ1)

# Графічний інтерфейс
def виконати_дію(дія):
    текст = поле_тексту.get("1.0", tk.END).strip()
    ключ1 = поле_ключа1.get().strip()
    ключ2 = поле_ключа2.get().strip()

    if not текст or not ключ1 or not ключ2:
        messagebox.showerror("Помилка", "Введіть текст і обидва ключі.")
        return

    результат = подвійна_перестановка(текст, ключ1, ключ2, дія)

    поле_результату.delete("1.0", tk.END)
    поле_результату.insert(tk.END, результат)

вікно = tk.Tk()
вікно.title("Подвійна перестановка")

tk.Label(вікно, text="Введіть текст:").pack()
поле_тексту = tk.Text(вікно, height=5, width=50)
поле_тексту.pack()

tk.Label(вікно, text="Ключ 1:").pack()
поле_ключа1 = tk.Entry(вікно)
поле_ключа1.pack()

tk.Label(вікно, text="Ключ 2:").pack()
поле_ключа2 = tk.Entry(вікно)
поле_ключа2.pack()

tk.Button(вікно, text="Зашифрувати", command=lambda: виконати_дію("шифрувати")).pack()
tk.Button(вікно, text="Розшифрувати", command=lambda: виконати_дію("розшифрувати")).pack()

tk.Label(вікно, text="Результат:").pack()
поле_результату = tk.Text(вікно, height=5, width=50)
поле_результату.pack()

вікно.mainloop()
